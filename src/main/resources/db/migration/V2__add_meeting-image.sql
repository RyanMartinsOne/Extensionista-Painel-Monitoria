CREATE TABLE monitoria_image
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encontro_id  BIGINT                      NOT NULL,
    object_key   VARCHAR(255)                NOT NULL,
    content_type VARCHAR(100)                NOT NULL,
    size_bytes   BIGINT                      NOT NULL,
    upload_date  TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT uk_monitoria_image_encontro
        UNIQUE (encontro_id),

    CONSTRAINT uk_monitoria_image_object_key
        UNIQUE (object_key),

    CONSTRAINT fk_monitoria_image_encontro
        FOREIGN KEY (encontro_id)
            REFERENCES encontro (id)
);